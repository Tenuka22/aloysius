import {
  CmsButton,
  Field,
  FieldGrid,
  Panel,
  PanelHead,
  RecordList,
  RecordRow,
} from "@aloysius/ui/components/cms/cms-primitives";
import { FileUploader } from "@aloysius/ui/components/cms/file-uploader";
import {
  ScreenHead,
  ScreenWrap,
} from "@aloysius/ui/components/cms/screen-head";
import { FormDialog } from "@aloysius/ui/components/dialog";
import {
  useMutation,
  useQueryClient,
  useSuspenseQuery,
} from "@tanstack/react-query";
import { createFileRoute } from "@tanstack/react-router";
import { Suspense, useReducer, useRef, useState } from "react";

import { uploadImageFile } from "@/components/club/upload";
import { mutationErrorText } from "@/components/mutation-error";
import { orpc } from "@/utils/orpc";

/**
 * `/cms/facilities` - the facilities showcase on `/academics`.
 *
 * Replaces `FACILITIES`, a fixed twelve-row shipped array whose photographs
 * were the only CMS-editable part - one image field per row, generated by
 * `ACADEMICS_FACILITY_FIELDS` and edited as a "Media grid" block on
 * `/cms/academics`. This is a roster instead, the same shape change
 * `/cms/academic-heads` and `/cms/sport-tiles` made to their own fixed
 * arrays: any number of facilities, each with its own name, tag, description,
 * photo and `sortOrder`.
 */

const blankOrNull = (value: string) => value.trim() || null;

interface FacilityFormState {
  name: string;
  tag: string;
  description: string;
  sortOrder: string;
  imageId: string | null;
  imagePreviewUrl: string | null;
}

const EMPTY_FACILITY: FacilityFormState = {
  name: "",
  tag: "",
  description: "",
  sortOrder: "0",
  imageId: null,
  imagePreviewUrl: null,
};

/** A row being edited, with the id the mutation needs. */
interface EditingFacility extends FacilityFormState {
  id: string;
}

interface FacilityDialogProps {
  editing: EditingFacility | null;
  onClose: () => void;
  onSaved: () => void;
  open: boolean;
}

const FacilityDialog = ({
  editing,
  onClose,
  onSaved,
  open,
}: FacilityDialogProps) => {
  const [form, patch] = useReducer(
    (state: FacilityFormState, statePatch: Partial<FacilityFormState>) => ({
      ...state,
      ...statePatch,
    }),
    editing ?? EMPTY_FACILITY
  );

  const create = useMutation(
    orpc.cms.createFacility.mutationOptions({
      onSuccess: () => {
        onSaved();
        onClose();
      },
    })
  );
  const update = useMutation(
    orpc.cms.updateFacility.mutationOptions({
      onSuccess: () => {
        onSaved();
        onClose();
      },
    })
  );

  const busy = create.isPending || update.isPending;
  const canSubmit =
    form.name.trim().length > 0 && form.tag.trim().length > 0 && !busy;

  const payload = {
    name: form.name.trim(),
    tag: form.tag.trim(),
    description: blankOrNull(form.description),
    sortOrder: Math.trunc(Number(form.sortOrder)) || 0,
    imageId: form.imageId,
  };

  return (
    <FormDialog
      busy={busy}
      description="Live on the Academics page the moment it is saved — published by the College's own office, so there is no review queue."
      error={mutationErrorText(
        editing ? update.error : create.error,
        "The facility could not be saved."
      )}
      onClose={onClose}
      onSubmit={() => {
        if (editing) {
          update.mutate({ id: editing.id, ...payload });
        } else {
          create.mutate(payload);
        }
      }}
      open={open}
      submitDisabled={!canSubmit}
      submitLabel={editing ? "Save changes" : "Publish"}
      title={editing ? "Edit facility" : "Add facility"}
    >
      <FieldGrid>
        <Field
          kind="text"
          label="Name"
          onChange={(next) => patch({ name: next })}
          value={form.name}
        />
        <Field
          hint='Shown as a tag on the photograph, e.g. "Science".'
          kind="text"
          label="Tag"
          onChange={(next) => patch({ tag: next })}
          value={form.tag}
        />
        <Field
          kind="textarea"
          label="Description"
          onChange={(next) => patch({ description: next })}
          value={form.description}
          wide
        />
        <Field
          hint="Lower numbers come first in the showcase list."
          kind="text"
          label="Order"
          onChange={(next) => patch({ sortOrder: next })}
          value={form.sortOrder}
        />
        <FileUploader
          clearable
          label="Photograph"
          onChange={(next) => patch({ imageId: next, imagePreviewUrl: null })}
          onUpload={uploadImageFile}
          previewUrl={form.imagePreviewUrl}
          ratioKey="principalPortrait"
          value={form.imageId}
          wide
        />
      </FieldGrid>
    </FormDialog>
  );
};

const FacilitiesContent = () => {
  const queryClient = useQueryClient();
  const listQuery = orpc.cms.listFacilities.queryOptions();
  const { data: facilities } = useSuspenseQuery(listQuery);
  const [dialog, setDialog] = useState<{
    editing: EditingFacility | null;
    open: boolean;
    token: number;
  }>({ editing: null, open: false, token: 0 });
  const openToken = useRef(0);

  const remove = useMutation(
    orpc.cms.deleteFacility.mutationOptions({
      onSuccess: () => queryClient.invalidateQueries(listQuery),
    })
  );

  return (
    <>
      <ScreenHead
        eyebrow="Content"
        heading="Facilities"
        note="The laboratories, libraries and specialist spaces shown in the Academics page showcase, in display order."
      />
      <Panel>
        <PanelHead
          action={
            <CmsButton
              onClick={() =>
                setDialog({
                  editing: null,
                  open: true,
                  token: (openToken.current += 1),
                })
              }
              tone="primary"
            >
              Add facility
            </CmsButton>
          }
          title="Facilities"
        />
        {facilities.length === 0 ? (
          <p>
            Nothing published yet. The Academics page shows no facilities
            showcase until the first facility is added.
          </p>
        ) : (
          <RecordList label="Facilities">
            {facilities.map((row) => (
              <RecordRow
                actions={
                  <>
                    <CmsButton
                      onClick={() =>
                        setDialog({
                          editing: {
                            description: row.description ?? "",
                            id: row.id,
                            imageId: null,
                            imagePreviewUrl: row.imageUrl,
                            name: row.name,
                            sortOrder: String(row.sortOrder),
                            tag: row.tag,
                          },
                          open: true,
                          token: (openToken.current += 1),
                        })
                      }
                      tone="quiet"
                    >
                      Edit
                    </CmsButton>
                    <CmsButton
                      disabled={remove.isPending}
                      onClick={() => remove.mutate({ id: row.id })}
                      tone="danger"
                    >
                      Remove
                    </CmsButton>
                  </>
                }
                key={row.id}
                meta={`${row.tag} · Order ${row.sortOrder}`}
                name={row.name}
              />
            ))}
          </RecordList>
        )}
      </Panel>
      <FacilityDialog
        editing={dialog.editing}
        key={dialog.token}
        onClose={() => setDialog((current) => ({ ...current, open: false }))}
        onSaved={() => queryClient.invalidateQueries(listQuery)}
        open={dialog.open}
      />
    </>
  );
};

export const Route = createFileRoute("/cms/facilities")({
  head: () => ({
    meta: [
      { title: "Facilities — St. Aloysius' College" },
      { name: "robots", content: "noindex, nofollow" },
    ],
  }),
  component: () => (
    <ScreenWrap>
      <Suspense fallback={<div>Loading…</div>}>
        <FacilitiesContent />
      </Suspense>
    </ScreenWrap>
  ),
});
